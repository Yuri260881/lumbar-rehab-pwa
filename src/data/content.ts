/**
 * Picks today's tip deterministically by date so it is stable during the day
 * and does not depend on random state.
 */
export function tipForDate(dateKey: string): string {
  let hash = 0;
  for (let index = 0; index < dateKey.length; index += 1) {
    hash = (hash * 31 + dateKey.charCodeAt(index)) % 100000;
  }
  return DAILY_TIPS[hash % DAILY_TIPS.length];
}
