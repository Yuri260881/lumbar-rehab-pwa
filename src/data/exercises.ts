export const EXERCISES_BY_ID: Record<string, Exercise> = Object.fromEntries(
  EXERCISES.map((exercise) => [exercise.id, exercise]),
);

export function getExercise(id: string): Exercise | undefined {
  return EXERCISES_BY_ID[id];
}

export function exercisesByCategory(category: ExerciseCategoryIdOrAll): Exercise[] {
  return category === 'all'
    ? EXERCISES
    : EXERCISES.filter((exercise) => exercise.category === category);
}

export type ExerciseCategoryIdOrAll =
  | Exercise['category']
  | 'all';
